(defn knight (max-x max-y x-0 y-0)
  (def points-count (* max-x max-y))
  (def p-0 (list x-0 y-0))
  (def all-directions '((2 1) (1 2) (-1 2) (-2 1) (-2 -1) (-1 -2) (1 -2) (2 -1)))
  (defn multiset ()
    (def init-codegen nil)
    (def x 1)
    (while (<= x max-x)
      (def y 1)
      (while (<= y max-y)
        (set! init-codegen (cons 0 init-codegen))
        (set! init-codegen (cons (symbol (++ "p-" x "-" y)) init-codegen))
        (+= y 1))
      (+= x 1))
    (eval (cons def init-codegen))
    (def total-count 0)
    (def distinct-count 0)
    (defn add (pos)
      (def sym (symbol (++ "p-" (car pos) "-" (car (cdr pos)))))
      (def val (eval sym))
      (+= total-count 1)
      (cond
        (= val 0) (+= distinct-count 1)
        nil)
      (eval (list set! sym (+ val 1))))
    (defn remove (pos)
      (def sym (symbol (++ "p-" (car pos) "-" (car (cdr pos)))))
      (def val (eval sym))
      (when (> val 0)
        (-= total-count 1)
        (cond
          (= val 1) (-= distinct-count 1)
          nil)
        (eval (list set! sym (- val 1)))))
    (lambda (input) (eval input)))
  (defn set ()
    (def init-codegen nil)
    (def x 1)
    (while (<= x max-x)
      (def y 1)
      (while (<= y max-y)
        (def l all-directions)
        (while (not (nil? l))
          (def
            dx (car (car l))
            dy (car (cdr (car l))))
          (def
            x1 (+ x dx)
            y1 (+ y dy))
          (when (and (<= 1 x1 max-x) (<= 1 y1 max-y))
            (set! init-codegen (cons false init-codegen))
            (set! init-codegen
                  (cons (symbol (++ "s-" x "-" y "-" x1 "-" y1)) init-codegen)))
          (set! l (cdr l)))
        (+= y 1))
      (+= x 1))
    (eval (cons def init-codegen))
    (def count 0)
    (defn add (from to)
      (def
        sym (symbol
              (++ "s-" (car from) "-" (car (cdr from)) "-" (car to) "-" (car (cdr to)))))
      (def val (eval sym))
      (when (not val) (+= count 1) (eval (list set! sym true))))
    (defn remove (from to)
      (def
        sym (symbol
              (++ "s-" (car from) "-" (car (cdr from)) "-" (car to) "-" (car (cdr to)))))
      (def val (eval sym))
      (when val (-= count 1) (eval (list set! sym false))))
    (defn contains? (from to)
      (eval (symbol
              (++ "s-" (car from) "-" (car (cdr from)) "-" (car to) "-" (car (cdr to))))))
    (lambda (input) (eval input)))
  (def path-set (multiset))
  (def step-set (set))
  (defn has-step? (path from to) ((step-set 'contains?) from to))
  (defn bad-pos? (path pos)
    (not (and (<= 1 (car pos) max-x)
              (<= 1 (car (cdr pos)) max-y)
              (not (has-step? path (car path) pos)))))
  (defn good-path? (path)
    (and (= (car path) p-0) (= (path-set 'distinct-count) points-count)))
  ((path-set 'add) p-0)
  (def
    path (list p-0)
    dirs-stack (list all-directions)
    result nil)
  (while (not (nil? path))
    (cond
      (good-path? path) (set! result path path nil)
      (do (def unstepped-directions (car dirs-stack))
          (cond
            (nil? unstepped-directions)
              (do (when (not (nil? (cdr path)))
                    ((step-set 'remove) (car (cdr path)) (car path)))
                  ((path-set 'remove) (car path))
                  (set! path (cdr path) dirs-stack (cdr dirs-stack)))
            (do (def next-pos (zip-with + (car path) (car unstepped-directions)))
                (def next-dirs (cons (cdr unstepped-directions) (cdr dirs-stack)))
                (cond
                  (bad-pos? path next-pos) (set! dirs-stack next-dirs)
                  (do ((step-set 'add) (car path) next-pos)
                      ((path-set 'add) next-pos)
                      (set! path
                            (cons next-pos path)
                            dirs-stack
                            (cons all-directions next-dirs)))))))))
  result)