(defn carpet-demo ()
    (def w-s 0)
    (defn RGB (r g b) (python! (++ "(" (/ r 255.0) "," (/ g 255.0) "," (/ b 255.0) ")")))
    (def colors (list (RGB 255 255 255) (RGB 255 0 0) (RGB 255 255 0)
                      (RGB 0 255 0) (RGB 255 0 255) (RGB 0 0 175) (RGB 0 125 125)))
;;     (print turtle)

    (defn liner-maker (ig x y)
        (lambda (cmd xn yn) (cond
            (= cmd 'line-dd) (do ; (print x y (+ x xn) (+ y yn) )
                ((ig "goto") (+ x xn) (+ y yn))
;;             (java ig "drawLine" x y (+ x xn) (+ y yn))
                (set! x (+ x xn) y (+ y yn)))
            (= cmd 'set-pos) (set! x xn y yn)
            (= cmd 'set-color)
;;                 (java ig "setColor" xn)
               ((ig "color") xn)
                 )))
    (def liner (liner-maker ig 0 0))
;;     (liner ' line-dd -500 -500))
    (defn pause (n) nil)
    (defn draw (n var-e)
        (defn go (i d c p) (cond (<= i n) (do
            (def h (/ (* d c) 2))
            (liner ' set-pos (+ (/ w-s 2) (- 0 h) d) (- (/ w-s 2) h))
            (liner ' set-color (list-ref (- i 1) colors) 0)
            (defn l (i j) (liner ' line-dd (* i (/ d 2)) (* j (/ d 2)) ))
            (defn e-var (i j) (cond
                (= 1 var-e) (do (l (- 0 i j) (- i j)) (l (- i j) (+ i j)) )
                (= 2 var-e) (do (l (- 0 j j) (+ i i)) )
                (= 3 var-e) (do (l i j) (l (- 0 j j) (+ i i)) (l (- 0 i) (- 0 j)) )
                (= 4 var-e) (do (l (- 0 i) (- 0 j)) (l (- 0 j j) (+ i i)) (l i j) )
                (= 5 var-e) (do (l i j) (l (- i j) (+ i j)) (l (- 0 i j) (- i j)) (l (- 0 i) (- 0 j)) )
                (= 6 var-e) (do (l i j) (l (- 0 i j) (- i j)) (l (- i j) (+ i j)) (l (- 0 i) (- 0 j)) )
                (do (l (/ (- 0 i j) 2) (/ (- i j) 2)) (l (- 0 j) i) (l (/ (- i j) 2) (/ (+ i j) 2)) ) ))
            (defn e (i j) (e-var i j)); (java window "repaint") (pause p))
            (defn f (i j n)
                (cond (> n 0) (do
                    (f      i      j  (- n 1))  (l (+ i j) (- j i))
                    (f      j (- 0 i) (- n 1))  (e j (- 0 i))
                    (f (- 0 j)     i  (- n 1))  (l (- i j) (+ i j))
                    (f      i      j  (- n 1)) ) ""))
            (defn carpet (i) (f 1 1 i) (e 1 1) (f -1 -1 i) (e -1 -1))
            (carpet i)
            (go (+ 1 i) (/ d 2) (+ 1 (* 2 c)) (/ p 3))
            ) "End"))
        (go 1 128 3 729))
    ;(draw 6 7);
